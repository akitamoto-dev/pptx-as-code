// 最小の例。ヘルパーの基本的な使い方を示す。
// 実際の資料は、この型を複製して deck-src/<名前>.js に書く。
module.exports = function (pres, L) {
  const s = L.slide();

  L.title(s, "スライドの組み立て方");
  L.keymsg(s, "ヘルパーを呼ぶだけで、所定の位置と書式が適用されます");

  L.sec(s, "構成要素", 2.0);
  L.BODY(s, "1 枚のスライドは、タイトル・キーメッセージ・見出し・本文の順に積む。座標と文字サイズはテーマが持つため、定義側では指定しない。", 2.44, 0.6);

  L.BULLETS(s, [
    "【タイトル】　その 1 枚で扱う内容を名詞で書く",
    "【キーメッセージ】　主語と述語のある文で、最も伝えたいことを書く",
    "【本文】　根拠・条件・補足を説明する",
  ], 3.3, 1.6);

  L.SRC(s, [{ text: "書式を変えるときは deck-src/theme.json を編集する" }]);
};
